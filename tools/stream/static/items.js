  var SIZE = ITEMS.size;

  // 32-bit FNV-1a over UTF-8 bytes (same as avatar.js and the Python port).
  function utf8(text) {
    var out = [];
    for (var i = 0; i < text.length; i++) {
      var c = text.charCodeAt(i);
      if (c >= 0xd800 && c <= 0xdbff && i + 1 < text.length) {
        var d = text.charCodeAt(i + 1);
        if (d >= 0xdc00 && d <= 0xdfff) { c = 0x10000 + ((c - 0xd800) << 10) + (d - 0xdc00); i++; }
      }
      if (c < 0x80) out.push(c);
      else if (c < 0x800) out.push(0xc0 | (c >> 6), 0x80 | (c & 63));
      else if (c < 0x10000) out.push(0xe0 | (c >> 12), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63));
      else out.push(0xf0 | (c >> 18), 0x80 | ((c >> 12) & 63), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63));
    }
    return out;
  }
  function hash(text) {
    var h = 0x811c9dc5, bytes = utf8(String(text));
    for (var i = 0; i < bytes.length; i++) { h ^= bytes[i]; h = Math.imul(h, 0x01000193) >>> 0; }
    return h >>> 0;
  }

  function parse(hex) {
    var n = parseInt(String(hex).slice(1), 16);
    return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
  }
  function hex(c) {
    var s = "#";
    for (var i = 0; i < 3; i++) s += (c[i] < 16 ? "0" : "") + c[i].toString(16);
    return s;
  }
  function mix(a, b, t) {
    return [0, 1, 2].map(function (i) { return Math.floor(a[i] + (b[i] - a[i]) * t + 0.5); });
  }
  function luma(c) { return (c[0] * 299 + c[1] * 587 + c[2] * 114) / 255000; }
  var BLACK = [0, 0, 0], WHITE = [255, 255, 255];

  // Five shades (outline, dark, mid, light, highlight) from one colour. Very dark materials (coal, crude oil)
  // get a lighter outline so they still read on the kit's dark slots.
  function ramp(color) {
    var c = parse(color), dark = luma(c) < 0.2;
    return [
      hex(dark ? mix(c, WHITE, 0.22) : mix(c, BLACK, 0.62)),
      hex(dark ? mix(c, BLACK, 0.25) : mix(c, BLACK, 0.3)),
      hex(c),
      hex(mix(c, WHITE, dark ? 0.2 : 0.32)),
      hex(mix(c, WHITE, dark ? 0.45 : 0.64)),
    ];
  }

  function humanize(name) {
    var s = String(name || "item").replace(/[-_]+/g, " ").trim();
    return s.charAt(0).toUpperCase() + s.slice(1);
  }
  function fallback(name) {
    var f = ITEMS.fallback, h = hash(String(name));
    return { label: humanize(name), t: f.t, c: f.colors[h % f.colors.length], color: f.colors[h % f.colors.length] };
  }
  function item(name) {
    return Object.prototype.hasOwnProperty.call(ITEMS.items, name) ? ITEMS.items[name] : fallback(name);
  }

  function palette(it) {
    var p = {};
    Object.keys(ITEMS.fixed).forEach(function (k) { p[k] = ITEMS.fixed[k]; });
    [["c", ITEMS.letters.c], ["c2", ITEMS.letters.c2], ["c3", ITEMS.letters.c3]].forEach(function (pair) {
      if (!it[pair[0]]) return;
      var r = ramp(it[pair[0]]);
      for (var i = 0; i < 5; i++) p[pair[1].charAt(i)] = r[i];
    });
    return p;
  }

  function pixels(name) {
    var it = item(name), pal = palette(it), rows = ITEMS.templates[it.t], grid = [];
    for (var y = 0; y < SIZE; y++) {
      grid.push([]);
      for (var x = 0; x < SIZE; x++) {
        var ch = rows[y].charAt(x);
        grid[y].push(ch === "." ? null : pal[ch] || null);
      }
    }
    return grid;
  }

  function esc(s) {
    return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
  }

  // One <path> per colour, horizontal runs merged; colours in order of first appearance.
  function svg(name, size, opts) {
    size = size || 32;
    opts = opts || {};
    var grid = pixels(name), order = [], runs = {};
    for (var y = 0; y < SIZE; y++) {
      var x = 0;
      while (x < SIZE) {
        var c = grid[y][x], w = 1;
        while (x + w < SIZE && grid[y][x + w] === c) w++;
        if (c) {
          if (!runs[c]) { runs[c] = ""; order.push(c); }
          runs[c] += "M" + x + " " + y + "h" + w + "v1h-" + w + "z";
        }
        x += w;
      }
    }
    var label = opts.title != null ? opts.title : item(name).label;
    var out = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ' + SIZE + " " + SIZE + '" width="' + size +
      '" height="' + size + '" shape-rendering="crispEdges" role="img" aria-label="' + esc(label) + '">';
    order.forEach(function (c) { out += '<path fill="' + c + '" d="' + runs[c] + '"/>'; });
    return out + "</svg>";
  }

